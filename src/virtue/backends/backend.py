"""The small, portable virtualization service contract."""

from typing import Protocol, Any


class BackendError(RuntimeError):
    """An actionable virtualization failure suitable for display to a user."""


class VirtualizationBackend(Protocol):
    host: Any

    def validate_profile(self, config: Any) -> None: ...
    def create(self, config: Any, progress=None) -> Any: ...
    def start(self, config: Any, safe_graphics: bool = False, *, display_mode: dict | None = None,
              fullscreen: bool = False) -> dict: ...
    def status(self, vm_id: str) -> dict: ...
    def shutdown(self, vm_id: str) -> None: ...
    def restart(self, vm_id: str) -> None: ...
    def pause(self, vm_id: str) -> None: ...
    def resume(self, vm_id: str) -> None: ...
    def force_stop(self, vm_id: str) -> None: ...
    def is_active(self, vm_id: str) -> bool: ...
    def prepare_offline(self, config: Any) -> None: ...
    def snapshot(self, config: Any, name: str) -> str: ...
    def list_snapshots(self, config: Any) -> list[str]: ...
    def restore_snapshot(self, config: Any, name: str) -> None: ...
    def expand_disk(self, config: Any, new_gib: int) -> None: ...
    def delete(self, config: Any) -> None: ...
    def setup_status(self, vm_id: str) -> dict | None: ...
    def setup_diagnostics(self, vm_id: str) -> dict[str, str]: ...
    def retry_setup(self, vm_id: str, repair_iso=None) -> bool: ...
    def display_status(self, vm_id: str) -> dict: ...
